"""Write ``docs/reference/verbs.md`` from the standard pack.

Everything on that page comes from the contracts themselves: each verb's ``VerbSpec``
(syntax, attributes, operators, constraints, ``WHERE`` support), its measurement mode, the
facts its ``derive`` declares and its examples, which the contract-completeness tests
execute. Run it after changing a verb:

    python scripts/gen_reference.py           # rewrite the page
    python scripts/gen_reference.py --check   # exit 1 if the page is out of date

``tests/conformance/test_docs_examples.py`` fails when the committed page differs.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from factlang.agent.reference import syntax
from factlang.contract import Contract, ContractPack
from factlang.packs.standard import standard_pack

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "reference" / "verbs.md"

GROUPS: tuple[tuple[str, str, tuple[str, ...]], ...] = (
    (
        "Structure facts",
        "Answered from the catalog; no data is scanned.",
        ("EXISTS", "TYPE"),
    ),
    (
        "Data-quality facts",
        "Measured over every row that matches the filter.",
        ("ROWS", "NULLS", "DEAD", "UNIQUE", "FANOUT", "VALUES", "RANGE", "PATTERN", "FRESH"),
    ),
    ("Relationship facts", "Measured on both sides of a key.", ("JOIN",)),
    (
        "Answer facts",
        "The numbers agents state in answers, with optional tolerance.",
        ("COUNT", "DISTINCT", "SUM", "AVG", "MIN", "MAX"),
    ),
    ("Semantic facts", "Recorded and hashed, never measured.", ("NOTE",)),
)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _mode(contract: Contract) -> str:
    if contract.plan is not None:
        return "measured with one read-only query"
    if contract.catalog_facts is not None:
        return "answered from the catalog"
    return f"unprobeable: {contract.unprobeable_reason}"


def _verb(contract: Contract) -> list[str]:
    spec = contract.spec
    out = [f"### {spec.name}", ""]
    if spec.summary:
        out += [spec.summary, ""]
    out += ["```text", syntax(spec), "```", ""]
    if spec.attrs:
        out += [
            "| attribute | value type | operators | required | meaning |",
            "|---|---|---|---|---|",
        ]
        for a in spec.attrs:
            ops = " ".join(f"`{_cell(op)}`" for op in a.ops) if a.ops else "none"
            out.append(
                f"| `{a.name}` | `{a.type}` | {ops} | {'yes' if a.required else 'no'} "
                f"| {_cell(a.doc)} |"
            )
        out.append("")
    notes = [f"Mode: {_mode(contract)}."]
    if contract.fact_names:
        notes.append("Facts: " + ", ".join(f"`{f}`" for f in contract.fact_names) + ".")
    notes.append(
        "Accepts a `WHERE` filter (always last on the line)."
        if spec.filterable
        else "Does not accept a `WHERE` filter."
    )
    notes += [f"`{a}` requires `{b}`." for a, b in spec.requires]
    notes += [f"`{a}` and `{b}` are mutually exclusive." for a, b in spec.exclusive]
    notes += [f"`{a}` and `{b}` go together and list as many columns." for a, b in spec.paired]
    out += [f"- {n}" for n in notes] + [""]
    valid = [e.source for e in contract.examples if e.valid]
    invalid = [e for e in contract.examples if not e.valid]
    if valid:
        out += ["```factlang", *valid, "```", ""]
    if invalid:
        out += ["| does not compile | diagnostic |", "|---|---|"]
        out += [f"| `{_cell(e.source)}` | `{e.expect}` |" for e in invalid]
        out.append("")
    return out


def render(pack: ContractPack | None = None) -> str:
    pack = pack if pack is not None else standard_pack()
    lines = [
        "# Verb reference",
        "",
        "<!-- Generated by scripts/gen_reference.py from the standard pack. Do not edit. -->",
        "",
        f"Pack `{pack.name}` version `{pack.version}`. Generated from each verb's contract, so "
        "it cannot drift from what the analyser accepts: every example below is executed by "
        "the contract-completeness tests. For a narrative tour, see "
        "[Standard verbs](../guide/verbs.md).",
        "",
        "In a syntax line, `[..]` is optional, `<TYPE>` is a value of that type and `a|b` are "
        "the operators the attribute accepts.",
        "",
    ]
    seen: set[str] = set()
    for title, blurb, names in GROUPS:
        contracts = [c for n in names if (c := pack.get(n)) is not None]
        if not contracts:
            continue
        lines += [f"## {title}", "", blurb, ""]
        for c in contracts:
            seen.add(c.name)
            lines += _verb(c)
    rest = [c for c in pack.contracts() if c.name not in seen and not pack.is_alias(c.name)]
    if rest:
        lines += ["## Other verbs", ""]
        for c in rest:
            lines += _verb(c)
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the page is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run scripts/gen_reference.py")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
